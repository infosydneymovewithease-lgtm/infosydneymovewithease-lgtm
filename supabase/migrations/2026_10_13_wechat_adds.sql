-- 2026-10-13 · 区分「应接待」和「实际接待」
--
-- 老板 10-13：
--   「接待多少人是需要看微信今日添加了多少个人的…
--     应该存在应接待和实际接待的区别，
--     实际接待就是微信添加我们公司账号的人数」
--
-- 原来只有一个「接待」数，把两件事混在一起了。实际是三段漏斗：
--
--   平台留言/咨询   小红书·朋友圈·视频号上有人问      → platform_inquiry（分平台）
--        ↓
--   加微信          真的加了「迁喜生活服务」          → 这次加的（不分平台）
--        ↓
--   下单                                            → orders（自动）
--
-- 中间那一跳的流失率才是有用的：平台问了 20 个只加了 5 个，
-- 说明文案或回复有问题。混成一个数就看不出来。
--
-- ⚠️ 为什么微信新增不分平台：
--    所有客户最后都转到同一个微信号「迁喜生活服务」，加好友时分不出来源。
--    硬要分只能靠问，那是另一个问题（企业微信的渠道活码能解决，以后再说）。

ALTER TABLE daily_work_log ADD COLUMN IF NOT EXISTS wechat_adds integer;

COMMENT ON COLUMN daily_work_log.wechat_adds IS
  '今天微信新增好友数 = 实际接待。空 = 还没填；0 = 今天确实一个都没加。
   不分平台，因为所有客户都进同一个微信号，加好友时分不出来源。';
